const FtxBand ftx_bands[FTX_NBANDS] = {
  /* name     key     lo        hi        FT8       FT4 */
  { "160 m", "160m",  1800000,  2000000,  1840000,        0 },
  { "80 m",  "80m",   3500000,  4000000,  3573000,  3575000 },
  { "60 m",  "60m",   5250000,  5450000,  5357000,  5357000 },
  { "40 m",  "40m",   7000000,  7300000,  7074000,  7047500 },
  { "30 m",  "30m",  10100000, 10150000, 10136000, 10140000 },
  { "20 m",  "20m",  14000000, 14350000, 14074000, 14080000 },
  { "17 m",  "17m",  18068000, 18168000, 18100000, 18104000 },
  { "15 m",  "15m",  21000000, 21450000, 21074000, 21140000 },
  { "12 m",  "12m",  24890000, 24990000, 24915000, 24919000 },
  { "10 m",  "10m",  28000000, 29700000, 28074000, 28180000 },
  { "6 m",   "6m",   50000000, 54000000, 50313000, 50318000 },
};

int ftx_band_for_hz(double hz)
{
  for (int i = 0; i < FTX_NBANDS; i++)
    if (hz >= ftx_bands[i].lo && hz <= ftx_bands[i].hi) return i;
  return -1;
}
